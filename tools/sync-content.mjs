#!/usr/bin/env node
/**
 * Pull the site text and images from the original React site (~/Website) into this
 * static site. Read-only on ~/Website: it only bundles src/content/*.ts in memory
 * with the esbuild already installed there, then writes:
 *   assets/js/content.js   →  window.SITE = { home, about, papers, ... }  (pure data)
 *   projects/<slug>/*.webp →  every image (and its -thumb) that the content references
 *
 * Usage:  node tools/sync-content.mjs [path/to/Website]     (default: ../Website)
 */
import { createRequire } from "node:module";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.resolve(here, "..");
const SRC = path.resolve(process.argv[2] || path.join(OUT, "..", "Website"));
const CONTENT = path.join(SRC, "src", "content");

if (!fs.existsSync(CONTENT)) {
  console.error(`No content folder at ${CONTENT}`);
  process.exit(1);
}

const require = createRequire(path.join(SRC, "package.json"));
const esbuild = require("esbuild");

// One virtual entry that re-exports every content module.
const modules = fs
  .readdirSync(CONTENT)
  .filter((f) => f.endsWith(".ts") && !f.endsWith(".d.ts"))
  .sort();
const entry = modules
  .map((f, i) => `export * as m${i} from ${JSON.stringify("./" + f)};`)
  .join("\n");

const result = await esbuild.build({
  stdin: { contents: entry, resolveDir: CONTENT, loader: "ts", sourcefile: "content-entry.ts" },
  bundle: true,
  format: "esm",
  platform: "neutral",
  write: false,
  tsconfig: path.join(SRC, "tsconfig.json"),
  logLevel: "warning",
});

const tmp = path.join(fs.mkdtempSync(path.join(os.tmpdir(), "site-sync-")), "content.mjs");
fs.writeFileSync(tmp, result.outputFiles[0].text);
const bundle = await import(pathToFileURL(tmp).href);
fs.rmSync(path.dirname(tmp), { recursive: true, force: true });

// Merge every data export (functions such as projectBySlug are dropped).
const site = {};
for (const ns of Object.values(bundle)) {
  for (const [key, value] of Object.entries(ns)) {
    if (typeof value === "function") continue;
    site[key] = value;
  }
}

const required = ["home", "about", "contact", "papers", "research", "auvs", "projectCatalog", "experience", "education", "skills", "stats"];
const missing = required.filter((k) => !(k in site));
if (missing.length) console.warn(`⚠ missing exports: ${missing.join(", ")} — pages will hide those parts.`);

// Copy every referenced image (and its thumbnail) from public/.
const json = JSON.stringify(site);
const refs = new Set(json.match(/projects\/[A-Za-z0-9_\-/]+\.(?:webp|png|jpe?g|gif|svg)/g) || []);
let copied = 0;
const absent = [];
for (const rel of refs) {
  for (const variant of [rel, rel.replace(/\.webp$/, "-thumb.webp")]) {
    const from = path.join(SRC, "public", variant);
    const to = path.join(OUT, variant);
    if (!fs.existsSync(from)) {
      if (variant === rel) absent.push(rel);
      continue;
    }
    fs.mkdirSync(path.dirname(to), { recursive: true });
    const a = fs.statSync(from);
    const b = fs.existsSync(to) ? fs.statSync(to) : null;
    if (!b || b.size !== a.size || b.mtimeMs < a.mtimeMs) {
      fs.copyFileSync(from, to);
      copied++;
    }
  }
}

// Remove images that are no longer referenced.
let removed = 0;
const projDir = path.join(OUT, "projects");
if (fs.existsSync(projDir)) {
  const keep = new Set([...refs].flatMap((r) => [r, r.replace(/\.webp$/, "-thumb.webp")]));
  for (const slug of fs.readdirSync(projDir)) {
    const dir = path.join(projDir, slug);
    for (const f of fs.readdirSync(dir)) {
      if (!keep.has(`projects/${slug}/${f}`)) {
        fs.rmSync(path.join(dir, f));
        removed++;
      }
    }
    if (!fs.readdirSync(dir).length) fs.rmdirSync(dir);
  }
}

const header =
  "/* GENERATED by tools/sync-content.mjs from ~/Website/src/content — do not edit by hand. */\n";
fs.writeFileSync(
  path.join(OUT, "assets", "js", "content.js"),
  `${header}window.SITE = ${JSON.stringify(site, null, 1)};\n`,
);

// sitemap.xml for search engines
const SITE_URL = "https://samyakkumarb.github.io/";
const urls = [
  SITE_URL,
  ...(site.papers || []).map((p) => `${SITE_URL}paper.html?p=${encodeURIComponent(p.slug)}`),
  ...(site.projectCatalog || []).map((p) => `${SITE_URL}project.html?p=${encodeURIComponent(p.slug)}`),
];
fs.writeFileSync(
  path.join(OUT, "sitemap.xml"),
  `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls
    .map((u) => `  <url><loc>${u.replace(/&/g, "&amp;")}</loc></url>`)
    .join("\n")}\n</urlset>\n`,
);

console.log(
  `✓ content.js: ${Object.keys(site).length} exports, ${site.projectCatalog?.length ?? 0} projects, ${site.papers?.length ?? 0} papers`,
);
console.log(`✓ images: ${refs.size} referenced, ${copied} copied, ${removed} removed`);
if (absent.length) console.warn(`⚠ referenced but not found in public/: ${absent.join(", ")}`);
